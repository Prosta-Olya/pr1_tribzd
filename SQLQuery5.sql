-- Просмотр таблицы уценка

SELECT 
    u.id_уценки,
    t.название AS [Товар],
    s.id_хранения,
    s.[дата поступления],
    u.[дата уценки],
    u.[коэф уценки],
    u.[новая цена]
FROM Уценка u
JOIN Хранение s ON u.id_хранения = s.id_хранения
JOIN Товары t ON s.id_товара = t.id_товара;


